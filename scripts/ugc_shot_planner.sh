#!/usr/bin/env bash
# ugc_shot_planner.sh
# -----------------------------------------------------------------------------
# Claude-headless SHOT PLANNER for UGC / video jobs. Gives the COMPOSITION
# DECISION to Claude instead of a weak brain (MiniMax) that collapses every
# format into one default. Claude reads the request, picks the format, sets how
# many PEOPLE are in frame, decides how many camera ANGLES/FRAMES are needed, and
# writes a ready-to-paste, ratio-correct Codex-format image prompt for EACH
# frame. The agent then hands each prompt to the user (human-in-the-loop) to generate.
#
# Formats it knows (and can extend):
#   talking_head     - ONE person only, direct to camera. NEVER a second person.
#   street_interview - EXACTLY two people: interviewer frame-LEFT w/ handheld mic,
#                      guest frame-RIGHT. Public setting. One anchor per location.
#   podcast          - studio set, 1-3 people at a table w/ pro mics; MULTIPLE
#                      angles -> multiple anchor frames (wide establishing shot,
#                      host close-up, guest close-up, optional over-shoulder),
#                      all the SAME people / wardrobe / set for continuity.
#
# USAGE
#   ugc_shot_planner.sh --request "<what the user asked for>" [--product "..."] \
#       [--context "..."] [--format auto|talking_head|street_interview|podcast] \
#       [--aspect 9:16] --out <plan.json> [--model opus|sonnet]
#
# OUTPUT: <plan.json> = { format, people, rationale, frames:[{id,label,role,
#   image_prompt, when_to_use}], continuity_notes }. Prints a human summary +
#   the prompt(s) to hand the user. exit 0 = planned, 1 = failed.
# -----------------------------------------------------------------------------
set -uo pipefail
CLAUDE_BIN="${CLAUDE_BIN:-claude}"
. "$HOME/.openclaw/scripts/ugc_engine_lib.sh"
ENGINE="${UGC_DELIVER_ENGINE:-auto}"
GEMINI_MODEL="${UGC_GEMINI_MODEL:-gemini-2.5-pro}"
REQUEST="" PRODUCT="" CONTEXT="" FORMAT="auto" ASPECT="9:16" OUT="" MODEL="" DRYRUN=0 CONTINUITY="auto"
while [[ $# -gt 0 ]]; do case "$1" in
  --request) REQUEST="$2"; shift 2;; --product) PRODUCT="$2"; shift 2;;
  --context) CONTEXT="$2"; shift 2;; --format) FORMAT="$2"; shift 2;;
  --continuity) CONTINUITY="$2"; shift 2;;
  --aspect) ASPECT="$2"; shift 2;; --out) OUT="$2"; shift 2;;
  --model) MODEL="$2"; shift 2;; --dry-run) DRYRUN=1; shift;;
  --engine) ENGINE="$2"; shift 2;; --gemini-model) GEMINI_MODEL="$2"; shift 2;;
  -h|--help) sed -n '2,32p' "$0"; exit 0;; *) echo "unknown arg: $1" >&2; exit 2;; esac; done
[[ -z "$REQUEST" || -z "$OUT" ]] && { echo "ERROR: --request and --out required" >&2; exit 2; }
validate_engine "$ENGINE"
# Claude absence is only fatal when the engine is forced to claude; auto falls back to Gemini.
[[ "$ENGINE" == "claude" && ! -x "$CLAUDE_BIN" ]] && { echo "ERROR: --engine claude but claude CLI not at $CLAUDE_BIN" >&2; exit 2; }
OUT="$(cd "$(dirname "$OUT")" 2>/dev/null && pwd || echo .)/$(basename "$OUT")"

# Photorealism Engine v2.0 directives (generated by sync_photorealism_engine.py). Read at
# runtime so the planner stays in sync; fall back to a short inline copy if the files are gone.
PHOTO_DIR="$HOME/.openclaw/photorealism"
UGC_DIRECTIVES="$(cat "$PHOTO_DIR/ugc_anchor_directives.txt" 2>/dev/null)"
[[ -z "$UGC_DIRECTIVES" ]] && UGC_DIRECTIVES="PHOTOREALISM (UGC): shot on an iPhone, real handheld phone-video, vertical; NOT illustration/3D render/studio/ad mockup/cinematic/glossy. Visible skin pores, slight asymmetry, brow/lash hairs, flyaways, eye moisture, minor blemishes, slight clothing wrinkles; NO flawless/airbrushed/plastic skin, NO perfect symmetry. Candid, unposed; no influencer smile. Real-world/practical light, soft falloff; no dramatic/hero lighting, no orange-and-teal. Real color science, natural skin tones; no hyper-saturation, no AI aesthetic. Slightly imperfect framing/crop. No text/logos/captions/watermark. Negative: NOT CGI, NOT 3D render, NOT illustration, NOT beauty retouched, NOT glamour/fashion/influencer photography, NOT AI aesthetic, NOT plastic skin, NOT overprocessed. NEVER use: masterpiece, stunning, gorgeous, beautiful, perfect, epic, breathtaking, award-winning, ultra cinematic, insanely detailed, best quality, viral, trending."
PODCAST_DIRECTIVES="$(cat "$PHOTO_DIR/podcast_anchor_directives.txt" 2>/dev/null)"
[[ -z "$PODCAST_DIRECTIVES" ]] && PODCAST_DIRECTIVES="PHOTOREALISM (podcast/editorial): RAW professional documentary photograph, full-frame, 35mm/50mm lens, f/2.8-f/4, natural depth of field and dynamic range; still photoreal, NOT a render, NOT glossy. Same human-realism, expression, color, negative-prompt, and forbidden-word rules as UGC. Lighting: soft key + ambient bounce, practical studio light, natural falloff, subtle rim; no epic/hero/movie-poster lighting, no orange-and-teal. Keep mics/equipment brief and secondary; the people are the subject."

PROMPT_FILE="$(mktemp -t ugc_shot_plan)"
trap 'rm -f "$PROMPT_FILE"' EXIT
cat > "$PROMPT_FILE" <<EOF
You are the SHOT PLANNER + anchor-prompt designer for a UGC/video job. The brain that
called you (MiniMax) is weak at composition and collapses every format into one lone
person. YOU make the composition decision and write the image prompt(s).

REQUEST: ${REQUEST}
Product: ${PRODUCT:-(n/a)}
Context: ${CONTEXT:-(n/a)}
Format hint: ${FORMAT}   (if "auto", infer it from the request)
Aspect ratio: ${ASPECT}  (vertical 9:16 unless the request clearly wants otherwise)

STEP 1 — pick the FORMAT and decide the people + angles. Rules (do not violate):
- talking_head: EXACTLY ONE person, direct to camera. NEVER a second person, never a mic pointed
  at someone else. 1 anchor frame (more only on scene change). Pick the right SUB-VARIANT from the
  request:
  - SELFIE / PHONE (default for "holding her phone", "filming herself", "selfie", "vlog", casual
    talk-to-camera): she holds her PHONE at arm's length and talks into the front camera (or the
    phone is propped close). Bedroom/room/handheld vibe, slightly high selfie angle, NO external
    mic. Do not add any mic.
  - EXPLAINER WITH DJI MIC (for "explaining", "tutorial", "creator setup", "talking head with a
    mic", a produced look): she sits/stands in a room explaining to camera, phone/camera on a
    tripod or propped (NOT in her hand). She wears a DJI Mic Mini — a tiny square clip-on wireless
    mic clipped to her top/collar, with the small fuzzy GREY furry windscreen (deadcat wind muff)
    on it. The mic is clipped on (worn), small and visible, NOT held, NOT a stage mic, no cable.
  If the request is ambiguous, default to SELFIE / PHONE.
- street_interview / public_interview: EXACTLY TWO people — interviewer on frame-LEFT, guest on
  frame-RIGHT, at natural distance. Public place (mall/street/campus). The interviewer holds a
  DJI Mic Mini — a TINY square clip-on wireless mic transmitter (about the size of a large coin /
  small matchbox) with a fuzzy GREY furry windscreen (small deadcat wind muff for noise reduction)
  on top, held in the fingertips and pointed toward the guest. The mic is ALWAYS visible but very
  small — NOT a big foam-ball stage mic, NOT a chunky karaoke/news mic, NOT an SM58, NOT a handheld
  stage mic, and NO visible cable. 1 anchor per distinct location; never one lone person.
- podcast: a real STUDIO set (acoustic foam/panels or tasteful backdrop, warm key + rim light,
  a table, professional mics on boom arms or desk stands, optional headphones). 1-3 people
  SEATED. Because a podcast is multi-cam, produce MULTIPLE anchor frames for the different
  ANGLES, all the SAME people + wardrobe + set: (a) wide establishing 2/3-shot, (b) host
  close-up, (c) guest close-up, and (d) an over-shoulder if 2 people. Note that frames b-d
  must keep identity/wardrobe/set identical to frame a.
- If the request is some other format, reason out the correct people count + angles yourself.

STEP 1.5 — decide EDIT CONTINUITY + ANGLE COVERAGE (this drives how many frames you make).
the user's continuity choice is: "${CONTINUITY}" (continuous | multiclip | auto).
- "continuous" = the finished video should read as ONE unbroken scene/take. The clips will be
  cut together, so every cut MUST land on a DIFFERENT camera angle/framing of the SAME moment
  (same person, wardrobe, set, lighting) — NEVER a cut back to the identical pose/position
  (that is the jump-cut artifact we are fixing). Produce a frame per beat at a distinct framing
  (e.g. wide establishing, medium, close-up on hands/face, profile, over-shoulder, low/high).
- "multiclip" = independent clips from the same generated image are fine; you still nudge
  framing variety so consecutive clips are not the identical pose.
- "auto" = YOU decide from CONTEXT + INTENT. Reason explicitly about (a) what is being shown
  and (b) how the viewer should feel, then pick:
    * Multi-person / multi-cam by nature (podcast, interview, street/public) → multiple ANGLES,
      treat as continuous multi-cam coverage.
    * Single-subject intimate/process moments (someone cooking, getting ready, a quiet demo)
      → lean "continuous": one flowing scene covered from a few angles (wide → medium → close
      on the hands/action), so it feels like a single take, not a slideshow of the same pose.
    * Fast punchy social cutdowns where energy > realism → "multiclip" is acceptable.
  State your choice and one line of reasoning in "rationale".
The capability note: the video model (MiniMax/Grok image_to_video) CANNOT cut between real
cameras on its own. The angle is only real if the STILL changes — so for continuous/multi-angle
plans you MUST emit a separate anchor frame per angle (re-posed/re-framed from the same identity),
and the agent generates each. Do not rely on the animator to invent the new angle.

STEP 2 — write the IMAGE PROMPT for EACH frame in our Codex anchor format:
- Begin with the ratio: "Generate ONE photorealistic vertical ${ASPECT} UGC <scene> still."
- State exactly who is in frame and WHERE (frame-left/right, seated positions), what they hold
  (mic for interview/podcast), the setting, and the camera angle for that frame.
- PHOTOREALISM IS MANDATORY (the goal is realism, not beauty or cinematic wow). For talking_head,
  selfie, and street_interview frames, apply the UGC DIRECTIVES below IN FULL. For podcast frames,
  apply the PODCAST DIRECTIVES below IN FULL. That means the capture style, human realism, lighting,
  color, composition, the negative prompt, AND the forbidden-word list.
- Each frame's image_prompt must be SELF-CONTAINED and ready to paste into image gen.

UGC DIRECTIVES (use for talking_head / selfie / street_interview frames):
${UGC_DIRECTIVES}

PODCAST DIRECTIVES (use for podcast frames):
${PODCAST_DIRECTIVES}

OUTPUT: write ONLY this JSON to ${OUT} (use the Write tool):
{
  "format": "<chosen>",
  "people": <int>,
  "continuity": "<continuous|multiclip>",
  "rationale": "<one line: why this format/people/angle count + continuity choice>",
  "frames": [
    {"id":"f1","label":"<e.g. wide 2-shot / talking head / host close-up>",
     "role":"<establishing|host|guest|...>","framing":"<wide|medium|close-up|over-shoulder|profile|POV>",
     "when_to_use":"<which clips use this anchor>",
     "image_prompt":"<full ready-to-paste Codex prompt with the ${ASPECT} ratio>"}
  ],
  "continuity_notes": "<how to keep identity/wardrobe/set consistent across frames + scene changes>"
}
Then print a short human summary: the format, people count, and how many frames. For EACH frame,
print its label on one line, then the FULL image_prompt INSIDE ITS OWN fenced triple-backtick code
block (so the user gets a tap-to-copy field on Telegram). Put ONLY the prompt text inside the fences —
no label, no commentary, no quotes inside the block. Example:
Frame f1 — talking head:
\`\`\`
<full image_prompt here>
\`\`\`
EOF

if [[ "$DRYRUN" -eq 1 ]]; then
  cat "$PROMPT_FILE"
  echo "--- out=$OUT model=${MODEL:-default} engine=$ENGINE (claude_live: $(claude_live && echo yes || echo no)) gemini=$GEMINI_MODEL"
  exit 0
fi

# Claude self-writes $OUT and prints the summary itself.
run_claude_planner() {
  echo "[shot-planner] engine=claude request='${REQUEST:0:50}' format=$FORMAT -> $OUT" >&2
  local cargs=(-p "$(cat "$PROMPT_FILE")" --allowedTools "Read Bash Write" \
               --permission-mode bypassPermissions --add-dir "$(dirname "$OUT")" --output-format text)
  [[ -n "$MODEL" ]] && cargs+=(--model "$MODEL")
  "$CLAUDE_BIN" "${cargs[@]}"
}

# Gemini returns pure JSON; we write it then regenerate the human summary + the
# per-frame fenced image_prompt blocks the user taps to copy (Telegram parity).
run_gemini_planner() {
  echo "[shot-planner] engine=gemini model=$GEMINI_MODEL request='${REQUEST:0:50}' -> $OUT" >&2
  python3 "$GEMINI_TEXT" --prompt-file "$PROMPT_FILE" --out "$OUT" --expect json \
    --require-keys format,people,frames --model "$GEMINI_MODEL" || return 1
  python3 - "$OUT" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
frames = d.get("frames", [])
print(f"format={d.get('format')} people={d.get('people')} "
      f"continuity={d.get('continuity')} frames={len(frames)}")
if d.get("rationale"):
    print(d["rationale"])
for fr in frames:
    label = fr.get("label") or fr.get("id", "frame")
    print(f"\nFrame {fr.get('id','?')} — {label}:")
    print("```")
    print((fr.get("image_prompt") or "").strip())
    print("```")
PY
}

case "$ENGINE" in
  claude) run_claude_planner;;
  gemini) run_gemini_planner;;
  auto)
    if claude_live; then
      run_claude_planner
      if ! valid_json "$OUT"; then
        echo "[shot-planner] claude produced no valid plan -> falling back to Gemini" >&2
        run_gemini_planner
      fi
    else
      echo "[shot-planner] claude CLI unavailable -> using Gemini" >&2
      run_gemini_planner
    fi
    ;;
esac

if valid_json "$OUT"; then
  echo "[shot-planner] OK: $OUT" >&2; exit 0
else
  echo "[shot-planner] FAILED: no valid JSON at $OUT" >&2; exit 1
fi
