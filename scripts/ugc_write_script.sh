#!/usr/bin/env bash
# ugc_write_script.sh
# -----------------------------------------------------------------------------
# Claude-headless SCRIPTWRITER for UGC ads. MiniMax writes stiff, ad-flavored
# dialogue; this offloads the WRITING to Claude (natively strong at natural
# speech) the same way ugc_claude_deliver.sh offloads vision. Use it for the
# Script stage of ugc-ad-strategist when this instance is on MiniMax.
#
# It writes the script package (per-beat dialogue + 6 hooks) as drop-in JSON that
# matches the ugc-ad-strategist brief_schema, so the strategist can merge it into
# brief.json directly.
#
# USAGE
#   ugc_write_script.sh --product "<name/desc>" --context "<audience/claim/angle/proof/lp_url>" \
#       [--brief <stageC_brief.json>] [--format testimonial|two_person_interview|street_interview] \
#       [--clips 6] [--voice <eleven_id>] [--lp <url>] [--industry ecommerce] \
#       --out <script.json> [--model opus|sonnet]
#
# OUTPUT: --out (JSON: base_still_prompt, clips[], hooks[], platform_cuts, voice, utm_map)
#   exit 0 = written + valid JSON, exit 1 = failed.
# -----------------------------------------------------------------------------
set -uo pipefail
CLAUDE_BIN="${CLAUDE_BIN:-claude}"
. "$HOME/.openclaw/scripts/ugc_engine_lib.sh"
ENGINE="${UGC_DELIVER_ENGINE:-auto}"
GEMINI_MODEL="${UGC_GEMINI_MODEL:-gemini-2.5-pro}"
STRAT="${UGC_STRATEGIST_DIR:-}"
for _c in "$HOME/.claude/skills/ugc-ad-strategist" "$HOME/.hermes/skills/marketing-and-ads/ugc-ad-strategist"; do
  [ -z "$STRAT" ] && [ -d "$_c" ] && STRAT="$_c"
done
[ -z "$STRAT" ] && STRAT="$HOME/.claude/skills/ugc-ad-strategist"
KILLER="$HOME/.claude/skills/killer-script-system/SKILL.md"

PRODUCT="" CONTEXT="" BRIEF="" FORMAT="testimonial" CLIPS="6" VOICE="kPzsL2i3teMYv0FxEYQ6"
LP="" INDUSTRY="ecommerce" OUT="" MODEL="" DRYRUN=0 ASPECT="9:16"
while [[ $# -gt 0 ]]; do case "$1" in
  --product) PRODUCT="$2"; shift 2;; --context) CONTEXT="$2"; shift 2;;
  --brief) BRIEF="$2"; shift 2;; --format) FORMAT="$2"; shift 2;;
  --clips) CLIPS="$2"; shift 2;; --voice) VOICE="$2"; shift 2;;
  --aspect) ASPECT="$2"; shift 2;;
  --lp) LP="$2"; shift 2;; --industry) INDUSTRY="$2"; shift 2;;
  --out) OUT="$2"; shift 2;; --model) MODEL="$2"; shift 2;; --dry-run) DRYRUN=1; shift;;
  --engine) ENGINE="$2"; shift 2;; --gemini-model) GEMINI_MODEL="$2"; shift 2;;
  -h|--help) sed -n '2,30p' "$0"; exit 0;; *) echo "unknown arg: $1" >&2; exit 2;; esac; done

[[ -z "$OUT" ]] && { echo "ERROR: --out required" >&2; exit 2; }
[[ -z "$PRODUCT$BRIEF" ]] && { echo "ERROR: --product or --brief required" >&2; exit 2; }
validate_engine "$ENGINE"
# Claude absence is only fatal when the engine is forced to claude; auto falls back to Gemini.
[[ "$ENGINE" == "claude" && ! -x "$CLAUDE_BIN" ]] && { echo "ERROR: --engine claude but claude CLI not at $CLAUDE_BIN" >&2; exit 2; }
OUT="$(cd "$(dirname "$OUT")" 2>/dev/null && pwd || echo .)/$(basename "$OUT")"

# Precompute conditional text OUTSIDE the heredoc (avoids nested-quote parsing).
if [[ -n "$BRIEF" ]]; then
  BRIEF_LINE="- Read the Stage-C brief for claim/angle/audience/proof/objections: ${BRIEF}"
else
  BRIEF_LINE=""
fi
if [[ "$FORMAT" == *interview* ]]; then
  FORMAT_GUIDE="real Q&A. The host asks short questions; the guest THINKS before answering, hesitates, sometimes answers slightly sideways then lands it. They overlap and react naturally. Each speaker stays in character (do not blur who is who)."
else
  FORMAT_GUIDE="first-person past-tense testimonial. She is telling a friend what happened, not pitching. No second-person commands."
fi

# Photorealism Engine v2.0 UGC directives (generated by sync_photorealism_engine.py), read at
# runtime with an inline fallback so base_still_prompt always carries the realism rules.
UGC_DIRECTIVES="$(cat "$HOME/.openclaw/photorealism/ugc_anchor_directives.txt" 2>/dev/null)"
[[ -z "$UGC_DIRECTIVES" ]] && UGC_DIRECTIVES="PHOTOREALISM (UGC): shot on an iPhone, real handheld phone-video, vertical; NOT illustration/3D render/studio/ad mockup/cinematic/glossy. Visible skin pores, slight asymmetry, brow/lash hairs, flyaways, minor blemishes, slight clothing wrinkles; NO flawless/airbrushed/plastic skin, NO perfect symmetry. Candid, unposed; no influencer smile. Real-world/practical light, soft falloff; no dramatic/hero lighting, no orange-and-teal. Real color science, natural skin tones; no hyper-saturation, no AI aesthetic. Slightly imperfect framing/crop. No text/logos/captions/watermark. Negative: NOT CGI, NOT 3D render, NOT illustration, NOT beauty retouched, NOT glamour/fashion/influencer photography, NOT AI aesthetic, NOT plastic skin, NOT overprocessed. NEVER use: masterpiece, stunning, gorgeous, beautiful, perfect, epic, breathtaking, award-winning, ultra cinematic, insanely detailed, best quality, viral, trending."

PROMPT_FILE="$(mktemp -t ugc_script_prompt)"
trap 'rm -f "$PROMPT_FILE"' EXIT
cat > "$PROMPT_FILE" <<EOF
You are the SCRIPTWRITER for a UGC ad. Your one job: write copy that sounds like a
real person talking, not an ad. The reasoning brain that called you (MiniMax)
writes stiff marketing-speak; you are here because you write natural human speech.

CONTEXT
- Product: ${PRODUCT:-see brief}
- Format: ${FORMAT}   (testimonial = one person to camera; two_person_interview / street_interview = host + guest Q&A)
- Clips to write: ${CLIPS}
- Landing page: ${LP:-see brief/context}
- Extra context: ${CONTEXT:-(none, use the brief)}
${BRIEF_LINE}

METHOD (read these, then follow them):
- Killer-script psychology + 5 steps: ${KILLER}
- Beat template + the producer JSON contract: ${STRAT}/references/ad_package_template.md and ${STRAT}/references/brief_schema.json
  Match brief_schema EXACTLY (the producer consumes it).

NATURAL-DIALOGUE RUBRIC (this is the whole point — obey every line):
1. Write for the EAR. Say each line out loud in your head; if it sounds written, rewrite it.
2. Contractions always (I'm, it's, you're, didn't, gonna, kinda). Real people never say "I am not going to".
3. One thought per breath. Short. Then a longer one. Vary the rhythm; never three balanced clauses in a row.
4. Use natural connective filler sparingly and only where a real person breathes: "okay so", "honestly",
   "I'm not gonna lie", "the thing is", "wait". Do NOT sprinkle them on every line — that reads as fake too.
5. Be SPECIFIC and concrete, never generic. "I read it in two sittings on the train" beats "it was so valuable".
   Name a real moment, number, place, or small detail. Specifics are what make it sound true.
6. BANNED ad-voice (never use): unlock, transform, game-changer, elevate, supercharge, dive in, journey,
   revolutionary, "in today's world", "look no further", "say goodbye to", tidy tricolons, hashtag energy.
7. Let it be a little imperfect: a mid-thought pivot, a self-correction ("well, more like..."), a real
   reaction. Perfectly clean lines sound scripted.
8. ${FORMAT} shape: ${FORMAT_GUIDE}
9. Match the persona's register to the audience and the face (age, vibe). A 24-year-old does not talk like a brochure.
10. Hooks: the first 2 seconds must sound like a real person mid-thought, not a slogan. Start in motion.

WRITING RULES (house style — bake in as you write, hard constraints on every dialogue line, hook, CTA, overlay, grok_prompt):
First-person past-tense testimonial voice; no "you will/gets you"; no income/earnings claims; capability/process
framing only; truthful scarcity only; the persistent disclaimer "My results. Results vary." Paid CTA SPEAKS the price.

CLIP SIZING (QA Bank A1): seconds is EXACTLY 6 or 10. ~14-16 spoken words for 6s, ~24-28 for 10s. Never overstuff
a 6s clip (it chipmunks the voice). Each clip needs: id (c1..), seconds, beat (hook/proof/mechanism/escalation/
honest_8020/cta), dialogue, emotion (delivery), action (gesture/camera; LOCKED-OFF if a screen must stay pinnable),
grok_prompt (ready image_to_video prompt that ENDS with: says: "<dialogue>"), overlay (<=6 words burned caption).

BASE_STILL_PROMPT FORMAT (match our Codex anchor format exactly — this is the prompt the user pastes into
image gen, so it MUST be self-contained and carry the ratio): begin with the ratio up front, e.g.
"Generate ONE photorealistic vertical ${ASPECT} UGC <scene> still." For a street/public interview it is two
people: name positions explicitly (interviewer on frame-LEFT holding a small handheld mic; guest on
frame-RIGHT), the setting/background. ALWAYS include the ${ASPECT} ratio (vertical) — never omit it.
Then apply the PHOTOREALISM DIRECTIVES below IN FULL (capture style, human realism, lighting, color,
composition, the negative prompt, and the forbidden-word list). The goal is realism, not beauty or
cinematic wow:
${UGC_DIRECTIVES}

OUTPUT: write ONLY a JSON object to ${OUT} (use the Write tool) with keys:
base_still_prompt, clips[], hooks[] (exactly 6: h1..h6 across speed_flex, skeptic_reversal, contrast,
confession, cold_open, message_match; each <25 words with overlay + platform_note), platform_cuts
(paid{cta_line spoken-price, native_button:"Learn More", meta_safe_swaps[], tiktok_swaps[]},
organic{cta_line DM}, persistent_disclaimer), voice {id:"${VOICE}", model:"eleven_multilingual_v2",
settings:{stability:0.45,similarity:0.75,style:0.30}}, utm_map {meta, tiktok} off the landing page.
After writing the file, print: WROTE ${OUT} and one line on the natural-speech choices you made.
EOF

if [[ "$DRYRUN" -eq 1 ]]; then
  cat "$PROMPT_FILE"
  echo "--- model=${MODEL:-default} out=$OUT engine=$ENGINE (claude_live: $(claude_live && echo yes || echo no)) gemini=$GEMINI_MODEL"
  exit 0
fi

# Claude reads the method files via tools and Writes $OUT.
run_claude_writer() {
  echo "[scriptwriter] engine=claude product='${PRODUCT:0:40}' format=$FORMAT clips=$CLIPS -> $OUT" >&2
  local cargs=(-p "$(cat "$PROMPT_FILE")" --allowedTools "Read Bash Write" \
               --permission-mode bypassPermissions --add-dir "$(dirname "$OUT")" \
               --add-dir "$STRAT" --output-format text)
  [[ -n "$MODEL" ]] && cargs+=(--model "$MODEL")
  "$CLAUDE_BIN" "${cargs[@]}"
}

# Gemini has no file/bash tools, so we INLINE the method files the prompt referenced,
# then ask Gemini to return pure JSON.
run_gemini_writer() {
  echo "[scriptwriter] engine=gemini model=$GEMINI_MODEL product='${PRODUCT:0:40}' -> $OUT" >&2
  local AUG; AUG="$(mktemp -t ugc_script_aug)"
  {
    cat "$PROMPT_FILE"
    echo; echo "=== INLINED CONTEXT (the files the prompt told you to read; you have NO file tools, so use these verbatim) ==="
    local f
    for f in "$KILLER" "$STRAT/references/ad_package_template.md" "$STRAT/references/brief_schema.json"; do
      if [[ -f "$f" ]]; then echo; echo "----- FILE: $f -----"; cat "$f"; fi
    done
    if [[ -n "$BRIEF" && -f "$BRIEF" ]]; then echo; echo "----- FILE (Stage-C brief): $BRIEF -----"; cat "$BRIEF"; fi
    echo; echo "=== WRITING RULES (house style; treat every line as a hard rule on dialogue, hooks, CTA, overlays, grok_prompt) ==="
    echo "First-person past-tense testimonial voice; no 'you will/gets you'; no income/earnings claims; capability/process framing only; truthful scarcity only; the persistent disclaimer 'My results. Results vary.'; paid CTA SPEAKS the price."
    echo; echo "=== OUTPUT INSTRUCTION (overrides any earlier 'use the Write tool / print WROTE' wording) ==="
    echo "Return ONLY the JSON object described above with keys: base_still_prompt, clips, hooks (exactly 6), platform_cuts, voice, utm_map. No prose, no code fences."
  } > "$AUG"
  python3 "$GEMINI_TEXT" --prompt-file "$AUG" --out "$OUT" --expect json \
    --require-keys base_still_prompt,clips,hooks,platform_cuts,voice --model "$GEMINI_MODEL"
  local rc=$?
  rm -f "$AUG"
  return $rc
}

case "$ENGINE" in
  claude) run_claude_writer;;
  gemini) run_gemini_writer;;
  auto)
    if claude_live; then
      run_claude_writer
      if ! valid_json "$OUT"; then
        echo "[scriptwriter] claude produced no valid script -> falling back to Gemini" >&2
        run_gemini_writer
      fi
    else
      echo "[scriptwriter] claude CLI unavailable -> using Gemini" >&2
      run_gemini_writer
    fi
    ;;
esac

if valid_json "$OUT"; then
  echo "[scriptwriter] OK valid JSON: $OUT" >&2; exit 0
else
  echo "[scriptwriter] FAILED: no valid JSON at $OUT" >&2; exit 1
fi
