#!/usr/bin/env python3
"""
ugc_interview_prompt.py - Deterministic anchor-prompt builder for PUBLIC / STREET
INTERVIEW UGC stills.

WHY: a public/street interview is a TWO-PERSON format — an interviewer on the
left holding a handheld mic, a guest on the right answering. The UGC pipeline
otherwise defaults to a SINGLE talking-head spokesperson, and a weak brain
(MiniMax) keeps collapsing "street interview" into one lone person with no mic.
This script takes the composition out of the model's hands: it ALWAYS emits the
correct two-person, mic-in-hand, frame-left/right, 9:16 Codex-format prompt that
matches our known-good reference stills. The agent hands this verbatim to the user.

USAGE
  ugc_interview_prompt.py --topic "AI tools for managing money" --setting mall
  ugc_interview_prompt.py --topic "..." --setting street \
     --interviewer "young Black male creator, mid-20s, dark puffer jacket" \
     --guest "older man, 60s, grey beard, navy overcoat and scarf" \
     --aspect 9:16 --save /path/anchor_prompt.txt

Prints the ready-to-paste image prompt to stdout (and --save writes it too).
"""
import argparse, os, sys

# Photorealism Engine v2.0 directives — generated by sync_photorealism_engine.py and read at
# runtime so this stays in sync with every other initial-frame builder. FALLBACK below keeps
# the script working standalone if the file is missing.
PHOTO_DIRECTIVES_FILE = os.path.expanduser("~/.openclaw/photorealism/ugc_anchor_directives.txt")
PHOTO_FALLBACK = (
    "PHOTOREALISM (UGC / handheld) — the goal is realism, not beauty or cinematic wow. Apply: "
    "shot on an iPhone, real handheld phone-video, vertical, natural depth of field; NOT illustration, "
    "NOT 3D render, NOT studio, NOT ad mockup, NOT cinematic, NOT glossy. Human realism (highest "
    "priority): visible skin pores and texture variation, natural translucency, slight facial asymmetry, "
    "individual brow and lash hairs, flyaways, eye moisture, realistic lip texture, minor blemishes, real "
    "hand texture, slight clothing wrinkles; NO flawless skin, NO perfect symmetry, NO airbrushing, NO "
    "plastic skin. Expression: candid, mid-conversation, unposed; no influencer smile, no advertisement "
    "pose. Lighting: real-world / practical light, soft natural shadow falloff; no dramatic/hero/movie-"
    "poster lighting, no orange-and-teal grade. Color: real-world color science, natural skin tones, "
    "accurate white balance; no hyper-saturation, no cinematic grade, no AI aesthetic. Composition: "
    "slightly imperfect handheld framing and crop, authentic perspective. No readable text, logos, "
    "captions, subtitles, watermark, or on-screen graphics. Negative prompt: NOT CGI, NOT 3D render, NOT "
    "digital art, NOT illustration, NOT beauty retouched, NOT glamour/fashion/influencer photography, NOT "
    "AI aesthetic, NOT synthetic/plastic skin, NOT overprocessed. NEVER use these words: masterpiece, "
    "stunning, gorgeous, beautiful, perfect, epic, breathtaking, award-winning, ultra cinematic, insanely "
    "detailed, godlike, legendary, viral, trending, best quality."
)


def photo_directives():
    """Load the canonical UGC photorealism tail; fall back to the inline copy if missing."""
    try:
        with open(PHOTO_DIRECTIVES_FILE) as f:
            text = f.read().strip()
            if text:
                return text
    except OSError:
        pass
    return PHOTO_FALLBACK


SETTINGS = {
    "mall": "inside a modern shopping mall atrium — escalators, glass railings, storefronts and shoppers blurred into generic bokeh, bright indoor retail lighting",
    "street": "on a busy city sidewalk — storefronts, traffic lights and pedestrians blurred behind, natural daylight",
    "campus": "outside a university building — stone architecture and students blurred behind, overcast daylight",
    "foodcourt": "near a mall food court — seating, storefronts and diners blurred behind, mixed indoor lighting",
}

# Locked-in defaults that match the known-good reference stills.
DEFAULT_INTERVIEWER = ("young Black male creator, early-to-mid 20s, dark puffer jacket over a light top, "
                       "natural short hair")
DEFAULT_GUEST = ("an everyday passer-by being interviewed, plausibly dressed for the setting, "
                 "natural real face")

# Modern street/creator interview mic — a DJI Mic Mini with the grey furry wind muff.
MIC_SPEC = ("a DJI Mic Mini — a TINY square clip-on wireless microphone transmitter (about the size "
            "of a large coin / small matchbox) with a fuzzy GREY furry windscreen (a small deadcat "
            "wind muff for noise reduction) on top. He holds this little mic in his fingertips and "
            "points it toward the guest. It is very small and discreet — NOT a big foam-ball stage "
            "microphone, NOT a chunky karaoke/news mic, NOT an SM58, NOT a handheld stage mic, and "
            "has NO visible cable")


def build(topic, setting, interviewer, guest, aspect):
    scene = SETTINGS.get(setting, setting)
    return (
        f"Generate ONE photorealistic vertical {aspect} UGC public interview still.\n\n"
        f"Real phone-video style, handheld iPhone vertical frame. NOT illustration, NOT studio, "
        f"NOT an ad mockup, NOT cinematic, NOT glossy.\n\n"
        f"EXACTLY TWO people, both clearly in frame:\n"
        f"- INTERVIEWER on frame-LEFT: {interviewer}. He is holding {MIC_SPEC}, extended toward the "
        f"guest at natural interview distance (the mic is visible but small, roughly chest height, NOT "
        f"close to the camera). He faces the guest.\n"
        f"- GUEST on frame-RIGHT: {guest}. Standing and listening, body angled toward the interviewer, "
        f"mouth closed (about to answer).\n\n"
        f"Setting: {scene}.\n\n"
        f"This is the FIRST FRAME of a public street-interview video about: {topic}. It must read as a "
        f"plausible candid moment where the host has just asked a question and the guest is about to answer.\n\n"
        f"{photo_directives()}\n\n"
        f"Keep the microphone visible and believable."
    )


def main():
    ap = argparse.ArgumentParser(description="Build a two-person public/street interview anchor prompt")
    ap.add_argument("--topic", required=True, help="what the interview is about")
    ap.add_argument("--setting", default="mall", help="mall|street|campus|foodcourt or a freeform phrase")
    ap.add_argument("--interviewer", default=DEFAULT_INTERVIEWER)
    ap.add_argument("--guest", default=DEFAULT_GUEST)
    ap.add_argument("--aspect", default="9:16")
    ap.add_argument("--save", help="also write the prompt to this path")
    args = ap.parse_args()
    prompt = build(args.topic, args.setting, args.interviewer, args.guest, args.aspect)
    if args.save:
        with open(args.save, "w") as f:
            f.write(prompt + "\n")
    # Print inside a fenced code block so the agent relays it to the user as a
    # tap-to-copy field on Telegram (the --save file stays raw for the pipeline).
    print("```\n" + prompt + "\n```")


if __name__ == "__main__":
    main()
